    /// <summary>取某版本 + 等级的全部分块（块数、总码字、数据码字）。</summary>
    internal static List<(int Count, int Total, int Data)> GetRsBlocks(int version, int eccIndex)
    {
        var list = new List<(int, int, int)>();
        int row = (version - 1) * 4 + eccIndex;
        for (int g = 0; g < 2; g++)
        {
            int count = RsBlockTable[row, g * 3];
            if (count <= 0) break;
            list.Add((count, RsBlockTable[row, g * 3 + 1], RsBlockTable[row, g * 3 + 2]));
        }
        return list;
    }

    /// <summary>某版本 + 等级的数据码字总量（容量计算用，与分块表同源）。</summary>
    internal static int GetDataCodewords(int version, int eccIndex)
    {
        int sum = 0;
        foreach (var (count, _, data) in GetRsBlocks(version, eccIndex)) sum += count * data;
        return sum;
    }

    /// <summary>某版本对齐图案的中心坐标（去掉末尾占位 0）。</summary>
    internal static int[] GetPatternPositions(int version)
    {
        var list = new List<int>();
        for (int i = 0; i < 7; i++)
        {
            int value = PatternPositionTable[version - 1, i];
            if (value == 0) break;
            list.Add(value);
        }
        return list.ToArray();
    }
